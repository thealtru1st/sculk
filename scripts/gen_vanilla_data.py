#!/usr/bin/env python3
"""Generate Sculk's protocol tables from Mojang's data generator output.

Produce the input with the official server jar for the targeted version:

    java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar \
        --reports --server --output generated

then run:

    python3 scripts/gen_vanilla_data.py path/to/generated

Writes crates/sculk/src/vanilla.rs (block states, biome ids, synchronized
registry entries, and tags). The output is deterministic: entries are emitted
in sorted order so network ids are stable between runs.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "sculk" / "src" / "vanilla.rs"

# Registries sent during configuration. Entries are referenced through the
# client's built-in "minecraft:core" known pack, so only identifiers travel.
SYNCED_REGISTRIES = [
    "dimension_type",
    "worldgen/biome",
    "damage_type",
    "timeline",
    "world_clock",
    "trim_material",
    "jukebox_song",
    "instrument",
    "cat_variant",
    "cat_sound_variant",
    "chicken_variant",
    "chicken_sound_variant",
    "cow_variant",
    "cow_sound_variant",
    "frog_variant",
    "painting_variant",
    "pig_variant",
    "pig_sound_variant",
    "wolf_variant",
    "wolf_sound_variant",
    "zombie_nautilus_variant",
]

# Built-in registries whose tags the client uses for physics and interaction.
STATIC_TAG_REGISTRIES = ["block", "item", "fluid", "entity_type", "game_event"]

# Non-default block states the terrain generator needs by name.
EXTRA_STATES = {
    "GRASS_BLOCK_SNOWY": ("minecraft:grass_block", {"snowy": "true"}),
    "SPRUCE_LEAVES_PERSISTENT": ("minecraft:spruce_leaves", {"persistent": "true", "distance": "7", "waterlogged": "false"}),
    "OAK_LEAVES_PERSISTENT": ("minecraft:oak_leaves", {"persistent": "true", "distance": "7", "waterlogged": "false"}),
    "BIRCH_LEAVES_PERSISTENT": ("minecraft:birch_leaves", {"persistent": "true", "distance": "7", "waterlogged": "false"}),
}


def strip(name):
    return name.split(":", 1)[1] if ":" in name else name


def const_name(name):
    return strip(name).replace("/", "_").replace(".", "_").upper()


def rust_str_list(items, indent="        "):
    return "".join(f'{indent}"{item}",\n' for item in items)


def dynamic_entries(data_dir, registry):
    base = data_dir / registry
    return sorted(
        str(p.relative_to(base).with_suffix("")).replace("\\", "/")
        for p in base.rglob("*.json")
    )


def load_tags(data_dir, registry):
    base = data_dir / "tags" / registry
    tags = {}
    if not base.exists():
        return tags
    for p in base.rglob("*.json"):
        name = str(p.relative_to(base).with_suffix("")).replace("\\", "/")
        tags[name] = json.loads(p.read_text(encoding="utf-8"))["values"]
    return tags


def resolve_tags(raw, ids):
    resolved = {}

    def resolve(name, stack):
        if name in resolved:
            return resolved[name]
        if name in stack:
            raise SystemExit(f"tag cycle at {name}")
        out = []
        for value in raw[name]:
            required = True
            if isinstance(value, dict):
                required = value.get("required", True)
                value = value["id"]
            if value.startswith("#"):
                ref = strip(value[1:])
                if ref in raw:
                    out.extend(resolve(ref, stack | {name}))
                elif required:
                    raise SystemExit(f"missing tag {value} in {name}")
            else:
                key = strip(value)
                if key in ids:
                    out.append(ids[key])
                elif required:
                    raise SystemExit(f"missing entry {value} in {name}")
        seen = set()
        deduped = [v for v in out if not (v in seen or seen.add(v))]
        resolved[name] = deduped
        return deduped

    for name in sorted(raw):
        resolve(name, frozenset())
    return resolved


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    gen = pathlib.Path(sys.argv[1])
    reports = gen / "reports"
    data_dir = gen / "data" / "minecraft"
    blocks = json.loads((reports / "blocks.json").read_text(encoding="utf-8"))
    registries = json.loads((reports / "registries.json").read_text(encoding="utf-8"))

    out = []
    out.append("// @generated by scripts/gen_vanilla_data.py from Mojang data generator reports.\n")
    out.append("// Do not edit manually.\n")
    out.append("#![allow(dead_code, clippy::type_complexity)]\n\n")

    # Block states.
    out.append("/// Default block state ids, one per block.\npub mod block {\n")
    for name in sorted(blocks):
        default = next(s["id"] for s in blocks[name]["states"] if s.get("default"))
        out.append(f"    pub const {const_name(name)}: i32 = {default};\n")
    for const, (name, props) in sorted(EXTRA_STATES.items()):
        matches = [
            s["id"]
            for s in blocks[name]["states"]
            if all(s.get("properties", {}).get(k) == v for k, v in props.items())
        ]
        if len(matches) != 1:
            raise SystemExit(f"{const}: expected one state, found {matches}")
        out.append(f"    pub const {const}: i32 = {matches[0]};\n")
    out.append("}\n\n")

    # Synchronized registries.
    entries_by_registry = {r: dynamic_entries(data_dir, r) for r in SYNCED_REGISTRIES}
    out.append("/// Network ids of biomes (index in the synchronized biome registry).\npub mod biome {\n")
    for idx, name in enumerate(entries_by_registry["worldgen/biome"]):
        out.append(f"    pub const {const_name(name)}: i32 = {idx};\n")
    out.append("}\n\n")
    out.append("/// Network ids of dimension types.\npub mod dimension_type {\n")
    for idx, name in enumerate(entries_by_registry["dimension_type"]):
        out.append(f"    pub const {const_name(name)}: i32 = {idx};\n")
    out.append("}\n\n")

    out.append("/// Synchronized registries and their entry identifiers, in network-id order.\n")
    out.append("pub const REGISTRIES: &[(&str, &[&str])] = &[\n")
    for registry in SYNCED_REGISTRIES:
        out.append(f'    (\n        "{registry}",\n        &[\n')
        out.append(rust_str_list(entries_by_registry[registry], "            "))
        out.append("        ],\n    ),\n")
    out.append("];\n\n")

    # Tags.
    tag_sets = []
    for registry in SYNCED_REGISTRIES:
        raw = load_tags(data_dir, registry)
        if raw:
            ids = {name: i for i, name in enumerate(entries_by_registry[registry])}
            tag_sets.append((registry, resolve_tags(raw, ids)))
    for registry in STATIC_TAG_REGISTRIES:
        raw = load_tags(data_dir, registry)
        entries = registries[f"minecraft:{registry}"]["entries"]
        ids = {strip(name): e["protocol_id"] for name, e in entries.items()}
        tag_sets.append((registry, resolve_tags(raw, ids)))

    # Packet ids for every protocol state and direction.
    packets = json.loads((reports / "packets.json").read_text(encoding="utf-8"))
    out.append("/// Packet ids per protocol state; `cb` = clientbound, `sb` = serverbound.\npub mod packet {\n")
    for state in sorted(packets):
        out.append(f"    pub mod {state} {{\n")
        for direction, short in (("clientbound", "cb"), ("serverbound", "sb")):
            entries = packets[state].get(direction, {})
            if not entries:
                continue
            out.append(f"        pub mod {short} {{\n")
            for name, info in sorted(entries.items(), key=lambda kv: kv[1]["protocol_id"]):
                out.append(f"            pub const {const_name(name)}: i32 = {info['protocol_id']:#04x};\n")
            out.append("        }\n")
        out.append("    }\n")
    out.append("}\n\n")

    # Built-in registry ids used by the server.
    for registry in ("entity_type", "menu"):
        entries = registries[f"minecraft:{registry}"]["entries"]
        out.append(f"/// `minecraft:{registry}` network ids.\npub mod {registry} {{\n")
        for name, entry in sorted(entries.items(), key=lambda kv: kv[1]["protocol_id"]):
            out.append(f"    pub const {const_name(name)}: i32 = {entry['protocol_id']};\n")
        out.append("}\n\n")

    out.append("/// Tags per registry: (tag name, member network ids).\n")
    out.append("pub const TAGS: &[(&str, &[(&str, &[i32])])] = &[\n")
    for registry, tags in tag_sets:
        out.append(f'    (\n        "{registry}",\n        &[\n')
        for name in sorted(tags):
            members = ", ".join(str(v) for v in tags[name])
            out.append(f'            ("{name}", &[{members}]),\n')
        out.append("        ],\n    ),\n")
    out.append("];\n")

    OUT.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
